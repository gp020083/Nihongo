/**
 * Deterministically permutes the 4 options of a JLPT mock question based on a numeric seed
 * and updates `correctIndex` so `options[correctIndex]` remains the exact same correct answer.
 * This ensures correct answers are evenly distributed across choices 1, 2, 3, and 4.
 */
export function shuffleQuestionOptions(
  question: JlptMockExamQuestion,
  seed: number = 0
): JlptMockExamQuestion {
  if (!Array.isArray(question.options) || question.options.length !== 4) {
    return question;
  }

  // Deterministic permutation using question ID hash + seed
  let hash = Math.abs(Math.floor(seed));
  for (let i = 0; i < question.id.length; i++) {
    hash = (hash * 31 + question.id.charCodeAt(i)) >>> 0;
  }

  const indices = [0, 1, 2, 3];
  for (let i = indices.length - 1; i > 0; i--) {
    hash = (hash * 1664525 + 1013904223) >>> 0;
    const j = hash % (i + 1);
    const tmp = indices[i];
    indices[i] = indices[j];
    indices[j] = tmp;
  }

  const newOptions = indices.map((origIdx) => question.options[origIdx]);
  const newCorrectIndex = indices.indexOf(question.correctIndex);

  return {
    ...question,
    options: newOptions,
    correctIndex: newCorrectIndex >= 0 ? newCorrectIndex : 0,
  };
}

/**
 * Classifies whether a question matches a selected MockExamThemeId filter.
 */
export function matchesMockExamTheme(
  q: JlptMockExamQuestion,
  theme: MockExamThemeId
): boolean {
  if (theme === 'all') return true;
  const text = `${q.mondaiLabel} ${q.promptJp} ${q.passageJp || ''} ${q.audioScriptJp || ''}`;
  switch (theme) {
    case 'star_and_ab':
      return (
        text.includes('★') ||
        text.includes('組み立て') ||
        text.includes('統合理解') ||
        text.includes('比較') ||
        text.includes('情報検索') ||
        text.includes('文章の文法')
      );
    case 'business_mail':
      return /社内|メール|会議|企画書|部長|課長|研修|営業|ビジネス|取引|カタログ|見積/.test(
        text
      );
    case 'news_science':
      return /科学|研究|環境|脳|AI|技術|エネルギー|都市|統計|制度|キャッシュレス|テレワーク/.test(
        text
      );
    case 'daily_travel':
      return /駅|電車|新幹線|旅行|ホテル|動物園|プール|パン屋|スーパー|マンション|アパート|料金|案内/.test(
        text
      );
    case 'culture_essay':
      return /小説|芸術|文化|伝統|職人|図書館|習慣|コミュニケーション|沈黙|幸福|読書/.test(
        text
      );
    default:
      return true;
  }
}

export interface RandomizedMockPaperResult {
  paper: JlptMockExamQuestion[];
  nextSeenIds: string[];
  unseenCountUsed: number;
  remainingUnseenCount: number;
  totalLevelPoolSize: number;
  cycleReset: boolean;
  questionTypeTags: string[];
}

/**
 * Pure, deterministic-per-seed exam paper builder that:
 * 1. Filters `pool` by `level` and deduplicates by both `id` and `promptJp`.
 * 2. Prioritizes UNSEEN questions (`!seenIds.includes(q.id)`) within each of the 3 official JLPT sections
 *    (`vocab_grammar`, `reading`, `listening`) so consecutive mock exams NEVER repeat questions.
 * 3. Only resets/wraps around when the user has exhausted the unseen pool for that section.
 * 4. Permutes the 4 options of every selected question so correct answers are distributed across 1, 2, 3, and 4.
 */
export function buildRandomizedMockExamPaper(params: {
  pool: JlptMockExamQuestion[];
  level: JlptLevel;
  seenIds: string[];
  targetCount?: number;
  seed?: number;
  theme?: MockExamThemeId;
}): RandomizedMockPaperResult {
  const {
    pool,
    level,
    seenIds = [],
    targetCount = 12,
    seed = 1,
    theme = 'all',
  } = params;

  // Step 1: Filter by level and deduplicate by id and normalized promptJp
  const seenKeySet = new Set<string>();
  const levelPool: JlptMockExamQuestion[] = [];
  for (const item of pool) {
    if (item.level !== level) continue;
    const promptKey = `${item.section}::${item.promptJp.trim()}`;
    if (seenKeySet.has(item.id) || seenKeySet.has(promptKey)) continue;
    seenKeySet.add(item.id);
    seenKeySet.add(promptKey);
    levelPool.push(item);
  }

  const totalLevelPoolSize = levelPool.length;
  const clampedTarget = Math.min(Math.max(3, targetCount), totalLevelPoolSize || targetCount);

  // Proportional quotas across the 3 JLPT sections (e.g., 12 -> 5 vocab_grammar, 4 reading, 3 listening)
  const vocabTarget = Math.round(clampedTarget * (5 / 12));
  const readingTarget = Math.round(clampedTarget * (4 / 12));
  const listeningTarget = Math.max(1, clampedTarget - vocabTarget - readingTarget);

  const sectionQuotas: Record<JlptExamSectionId, number> = {
    vocab_grammar: vocabTarget,
    reading: readingTarget,
    listening: listeningTarget,
  };

  const previouslySeenSet = new Set(seenIds);
  let rngState = (Math.abs(Math.floor(seed)) || 1) >>> 0;
  const nextRand = () => {
    rngState = (rngState * 1664525 + 1013904223) >>> 0;
    return rngState;
  };

  const shuffleArray = <T,>(arr: T[]): T[] => {
    const copy = [...arr];
    for (let i = copy.length - 1; i > 0; i--) {
      const j = nextRand() % (i + 1);
      const tmp = copy[i];
      copy[i] = copy[j];
      copy[j] = tmp;
    }
    return copy;
  };

  const selectedQuestions: JlptMockExamQuestion[] = [];
  let unseenCountUsed = 0;
  let cycleReset = false;

  const sectionsOrder: JlptExamSectionId[] = ['vocab_grammar', 'reading', 'listening'];

  // Prepare shuffled unseen & seen lists per section
  const unseenBySec = {} as Record<JlptExamSectionId, JlptMockExamQuestion[]>;
  const seenBySec = {} as Record<JlptExamSectionId, JlptMockExamQuestion[]>;

  for (const sec of sectionsOrder) {
    const secAll = levelPool.filter((q) => q.section === sec);
    const unseenTheme = shuffleArray(
      secAll.filter((q) => !previouslySeenSet.has(q.id) && matchesMockExamTheme(q, theme))
    );
    const unseenOther =
      theme === 'all'
        ? []
        : shuffleArray(
            secAll.filter((q) => !previouslySeenSet.has(q.id) && !matchesMockExamTheme(q, theme))
          );
    unseenBySec[sec] = [...unseenTheme, ...unseenOther];

    const seenTheme = shuffleArray(
      secAll.filter((q) => previouslySeenSet.has(q.id) && matchesMockExamTheme(q, theme))
    );
    const seenOther =
      theme === 'all'
        ? []
        : shuffleArray(
            secAll.filter((q) => previouslySeenSet.has(q.id) && !matchesMockExamTheme(q, theme))
          );
    seenBySec[sec] = [...seenTheme, ...seenOther];
  }

  // Rebalance sectionQuotas toward sections that still have unseen questions
  // so we never repeat a question if total unseen across the level >= clampedTarget
  const totalUnseenAvailable =
    unseenBySec.vocab_grammar.length +
    unseenBySec.reading.length +
    unseenBySec.listening.length;

  if (totalUnseenAvailable >= clampedTarget) {
    let deficit = 0;
    for (const sec of sectionsOrder) {
      if (unseenBySec[sec].length < sectionQuotas[sec]) {
        deficit += sectionQuotas[sec] - unseenBySec[sec].length;
        sectionQuotas[sec] = unseenBySec[sec].length;
      }
    }
    while (deficit > 0) {
      let allocated = false;
      for (const sec of sectionsOrder) {
        if (unseenBySec[sec].length > sectionQuotas[sec] && deficit > 0) {
          sectionQuotas[sec]++;
          deficit--;
          allocated = true;
        }
      }
      if (!allocated) break;
    }
  } else {
    // Even when wrapping around (cycleReset), ensure no section quota exceeds total items in that section
    let totalCapDeficit = 0;
    for (const sec of sectionsOrder) {
      const secTotal = unseenBySec[sec].length + seenBySec[sec].length;
      if (secTotal < sectionQuotas[sec]) {
        totalCapDeficit += sectionQuotas[sec] - secTotal;
        sectionQuotas[sec] = secTotal;
      }
    }
    while (totalCapDeficit > 0) {
      let allocated = false;
      for (const sec of sectionsOrder) {
        const secTotal = unseenBySec[sec].length + seenBySec[sec].length;
        if (secTotal > sectionQuotas[sec] && totalCapDeficit > 0) {
          sectionQuotas[sec]++;
          totalCapDeficit--;
          allocated = true;
        }
      }
      if (!allocated) break;
    }
  }

  for (const sec of sectionsOrder) {
    const quota = sectionQuotas[sec];
    const unseenCombined = unseenBySec[sec];
    const seenCombined = seenBySec[sec];

    if (unseenCombined.length >= quota) {
      const picked = unseenCombined.slice(0, quota);
      selectedQuestions.push(...picked);
      unseenCountUsed += picked.length;
    } else {
      // Take all remaining unseen first, then wrap around from seen pool
      cycleReset = true;
      const pickedUnseen = [...unseenCombined];
      unseenCountUsed += pickedUnseen.length;
      const neededFromSeen = quota - pickedUnseen.length;
      selectedQuestions.push(...pickedUnseen, ...seenCombined.slice(0, neededFromSeen));
    }
  }

  // Permute options on each question so correctIndex is distributed across 0..3
  const permutedPaper = selectedQuestions.map((q, idx) =>
    shuffleQuestionOptions(q, seed * 97 + idx * 13 + 7)
  );

  // Update nextSeenIds: if cycleReset occurred, start fresh with current paper IDs; otherwise append
  const currentPaperIds = permutedPaper.map((q) => q.id);
  const nextSeenIds = cycleReset
    ? Array.from(new Set(currentPaperIds))
    : Array.from(new Set([...seenIds, ...currentPaperIds]));

  const nextSeenSet = new Set(nextSeenIds);
  const remainingUnseenCount = levelPool.filter((q) => !nextSeenSet.has(q.id)).length;

  // Summarize distinct question types present in this paper
  const questionTypeTags = Array.from(
    new Set(
      permutedPaper.map((q) => {
        const cleaned = q.mondaiLabel.replace(/^問題\d+・/, '');
        return cleaned;
      })
    )
  );

  return {
    paper: permutedPaper,
    nextSeenIds,
    unseenCountUsed,
    remainingUnseenCount,
    totalLevelPoolSize,
    cycleReset,
    questionTypeTags,
  };
}

